def addition(n1,n2):
    print(f"Addition of {n1} and {n2} : {n1+n2}")

def subtraction(n1,n2):
    print(f"Subtraction of {n1} and {n2} : {n1-n2}")

def division(n1,n2):
    print(f"Division of {n1} and {n2} : {n1/n2}")

def multiplication(n1,n2):
    print(f"Multiplication of {n1} and {n2} : {n1*n2}")
